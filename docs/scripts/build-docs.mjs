/* ------------------------------------------------------------------------ report */

console.log(`Built ${PAGES.length} pages → docs/`);
const kb = (n) => `${(n / 1024).toFixed(0)}kb`;
for (const s of stats) {
  console.log(
    `  ${s.slug.padEnd(16)} html ${kb(s.html).padStart(6)}   md ${kb(s.md).padStart(6)}   ` +
      `${s.sections} sections${s.widgets ? `, ${s.widgets} widget${s.widgets === 1 ? '' : 's'}` : ''}`,
  );
}
console.log(`\nWrote ${written.length} files. Open docs/index.html to read.`);
if (artifactUrls) console.log('Artifact bodies written to .artifact-build/');
