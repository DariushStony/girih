#!/usr/bin/env node
/**
 * Assemble the documentation.
 *
 * Nine self-contained HTML pages that share one design system, plus a Markdown mirror
 * that renders natively on GitHub. Both come from the same page modules and the same
 * extracted data, so the two flavours cannot drift apart in content — only in
 * interactivity, which Markdown cannot carry.
 *
 * This mirrors girih's own philosophy: docs/*.html and docs/md/*.md are build artifacts.
 * Edit docs/scripts/pages/*.mjs, then re-run this.
 *
 * Usage:
 *   node docs/scripts/build-docs.mjs
 *   node docs/scripts/build-docs.mjs --artifact-urls urls.json   also emit artifact bodies
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { PAGES, render } from './lib/shell.mjs';
import { toMarkdown } from './lib/tomarkdown.mjs';

const repoRoot = fileURLToPath(new URL('../..', import.meta.url));
const docsDir = join(repoRoot, 'docs');
const mdDir = join(docsDir, 'md');
const dataDir = join(docsDir, 'data');

/* ------------------------------------------------------------------ load data */

function loadJson(name, hint) {
  const path = join(dataDir, name);
  if (!existsSync(path)) {
    console.error(`Missing docs/data/${name} — run: ${hint}`);
    process.exit(1);
  }
  return JSON.parse(readFileSync(path, 'utf8'));
}

const tokens = loadJson('tokens.json', 'node docs/scripts/extract-tokens.mjs');
const diagnostics = loadJson('diagnostics.json', 'node docs/scripts/extract-diagnostics.mjs');

// One data object handed to every page module.
const data = {
  ...tokens,
  diagnostics,
  families: diagnostics.families,
  diagCount: diagnostics.total,
};

/* ------------------------------------------------------------- load page modules */

const modules = {};
for (const page of PAGES) {
  const mod = await import(new URL(`./pages/${page.slug}.mjs`, import.meta.url).href);
  modules[page.slug] = mod.default;
}

/* --------------------------------------------------------------------- artifact urls */

const urlFlagIndex = process.argv.indexOf('--artifact-urls');
const artifactUrls =
  urlFlagIndex !== -1 && process.argv[urlFlagIndex + 1] ? JSON.parse(readFileSync(process.argv[urlFlagIndex + 1], 'utf8')) : null;

/* ------------------------------------------------------------------------- build */

mkdirSync(docsDir, { recursive: true });
mkdirSync(mdDir, { recursive: true });

const written = [];
const stats = [];

for (const page of PAGES) {
  // A page may supply `mdBody` when its HTML cannot convert meaningfully — the quiz, whose
  // whole substance is an interactive widget, provides a static Q&A instead.
  const { sections, body, widgets = [], mdBody = null } = modules[page.slug](data);

  // Hoist widget CSS and JS out of the body so they land once, in the right place.
  const widgetCss = widgets
    .map((w) => w.css)
    .filter(Boolean)
    .join('\n');
  const widgetJs = widgets
    .map((w) => w.js)
    .filter(Boolean)
    .join('\n');

  const bodyWithCss = widgetCss ? `<style>\n${widgetCss}\n</style>\n${body}` : body;

  // --- standalone HTML -------------------------------------------------------
  const html = render(page, { mode: 'file', sections, body: bodyWithCss, scripts: widgetJs });
  const htmlPath = join(docsDir, `${page.slug}.html`);
  writeFileSync(htmlPath, html, 'utf8');
  written.push(htmlPath);

  // --- Markdown mirror -------------------------------------------------------
  const markdown =
    mdBody ??
    toMarkdown(body, {
      widgetNote: `Open [the interactive version](../${page.slug}.html) in a browser to use it.`,
    });

  const i = PAGES.findIndex((p) => p.slug === page.slug);
  const prev = i > 0 ? PAGES[i - 1] : null;
  const next = i < PAGES.length - 1 ? PAGES[i + 1] : null;
  const navLine = [
    prev ? `← [${prev.title}](${prev.slug}.md)` : null,
    '[Contents](README.md)',
    next ? `[${next.title}](${next.slug}.md) →` : null,
  ]
    .filter(Boolean)
    .join('  ·  ');

  const md = `<!-- Generated by docs/scripts/build-docs.mjs — edit docs/scripts/pages/${page.slug}.mjs instead. -->

# ${page.title}

> ${page.blurb}
>
> **This is the Markdown mirror.** The [interactive version](../${page.slug}.html) has live
> widgets — a brand switch, an alias-chain walker, a pipeline stepper, and a quiz — that
> Markdown cannot render.

${navLine}

---

${markdown}

---

${navLine}
`;

  const mdPath = join(mdDir, `${page.slug}.md`);
  writeFileSync(mdPath, md, 'utf8');
  written.push(mdPath);

  stats.push({
    slug: page.slug,
    html: html.length,
    md: md.length,
    widgets: widgets.filter((w) => w.html).length,
    sections: sections.length,
  });

  // --- artifact body (optional) ---------------------------------------------
  if (artifactUrls) {
    const artifactHtml = render(page, {
      mode: 'artifact',
      urls: artifactUrls,
      sections,
      body: bodyWithCss,
      scripts: widgetJs,
    });
    // Artifact bodies are a publishing intermediate, not a repo artifact — they go
    // wherever --artifact-out says, defaulting outside the working tree.
    const outFlag = process.argv.indexOf('--artifact-out');
    const outDir = outFlag !== -1 && process.argv[outFlag + 1] ? process.argv[outFlag + 1] : join(repoRoot, '.artifact-build');
    mkdirSync(outDir, { recursive: true });
    const p = join(outDir, `${page.slug}.html`);
    writeFileSync(p, artifactHtml, 'utf8');
    written.push(p);
  }
}

/* ------------------------------------------------------------------ docs indexes */

const contentsRows = PAGES.map((p) => {
  const html = p.slug === 'index' ? 'index.html' : `${p.slug}.html`;
  return `| ${p.n} | [**${p.title}**](md/${p.slug}.md) | ${p.blurb} | [interactive](${html}) |`;
}).join('\n');

