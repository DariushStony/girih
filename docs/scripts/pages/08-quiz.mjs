/**
 * Markdown cannot carry the click-to-reveal widget, so the mirror gets a genuine static
 * version instead of a stub: every question, every option, and the full feedback behind a
 * <details> element (which GitHub renders natively).
 */
function questionsAsMarkdown() {
  const strip = (html) =>
    html
      .replace(/<code>([\s\S]*?)<\/code>/g, (m, t) => `\`${t.replace(/<[^>]+>/g, '')}\``)
      .replace(/<\/?(b|strong)>/g, '**')
      .replace(/<\/?(i|em)>/g, '_')
      .replace(/<[^>]+>/g, '')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&amp;/g, '&')
      .replace(/\s+/g, ' ')
      .trim();

  return QUESTIONS.map((q, i) => {
    const letters = ['A', 'B', 'C', 'D'];
    const opts = q.options.map((o, oi) => `${letters[oi]}. ${strip(o.text)}`).join('\n');
    const feedback = q.options
      .map((o, oi) => `**${letters[oi]}** ${oi === q.answer ? '— ✅ correct' : '— ❌'} · ${strip(o.why)}`)
      .join('\n\n');
    const codeBlock = q.code ? `\n\`\`\`css\n${q.code}\n\`\`\`\n` : '';
    return `### Question ${i + 1}

${strip(q.stem)}
${codeBlock}
${opts}

<details>
<summary><b>Show answer and feedback</b></summary>

**Answer: ${letters[q.answer]}**

${feedback}

</details>`;
  }).join('\n\n---\n\n');
}

